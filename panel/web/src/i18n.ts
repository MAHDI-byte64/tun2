export const TABLES: Record<Lang, Table> = { fa, en };

export type Digits = "fa" | "latin";

/** Persian digits for a string of Latin ones, when the language and setting ask for them. */
export function localDigits(s: string, lang: Lang, digits: Digits): string {
  if (lang !== "fa" || digits === "latin") return s;
  return s.replace(/\d/g, (d) => FA_DIGITS[Number(d)]).replace(/\./g, "٫").replace(/,/g, "٬");
}

export { FA_DIGITS };
